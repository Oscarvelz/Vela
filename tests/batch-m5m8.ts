// Batch reader: date ranges, solo moments, Spanish dates (audit M5–M8). Fake data only.
// Run: node_modules/.bin/rolldown tests/batch-m5m8.ts --file /tmp/m.mjs --format esm --platform node && node /tmp/m.mjs
import { parseBatch } from "../src/lib/vela/batch";
const now = new Date(2026, 10, 2, 12, 0); // Mon Nov 2 2026
const ctx = { partners: ["Fakeana", "Fakelu", "Fakemar"] };
let pass = 0, fail = 0;
const ok = (name: string, cond: boolean, got: unknown) => { if (cond) pass += 1; else { fail += 1; console.log("FAIL", name, JSON.stringify(got)); } };
const P = (t: string, lang?: "en" | "es") => parseBatch(t, now, { ...ctx, lang });
let e = P("el 28 con Fakeana");
ok("el 28 → Oct 28", e[0]?.date === "2026-10-28" && e[0].partnerName === "Fakeana", e);
e = P("2/11 con Fakeana");
ok("2/11 Spanish line → Nov 2", e[0]?.date === "2026-11-02", e);
e = P("2/11 with Fakeana");
ok("2/11 English line → Feb 11", e[0]?.date === "2026-02-11", e);
e = P("2/11 Fakeana", "es");
ok("2/11 with the app in Spanish → Nov 2", e[0]?.date === "2026-11-02", e);
e = P("el finde con Fakelu");
ok("el finde on a Monday → Sat Oct 31", e[0]?.date === "2026-10-31", e);
e = P("last weekend with Fakelu");
ok("last weekend on a Monday → Sat Oct 31", e[0]?.date === "2026-10-31", e);
e = P("Oct 24, the weekend at the cabin with Fakelu");
ok("an explicit date beats 'the weekend'", e.length === 1 && e[0].date === "2026-10-24", e);
e = P("del 1 al 3 con Fakemar");
ok("del 1 al 3 on Nov 2 → the last full 1–3: Oct 1–3, 3 sessions", e.length === 1 && e[0].date === "2026-10-01" && e[0].endDate === "2026-10-03" && e[0].count === 3, e);
e = P("Oct 25 - Oct 26 weekend getaway with Fakeana, 5 times total");
ok("Oct 25 - Oct 26, 5 times → one entry Oct 25–26 ×5 with Fakeana", e.length === 1 && e[0].date === "2026-10-25" && e[0].endDate === "2026-10-26" && e[0].count === 5 && e[0].partnerName === "Fakeana", e);
e = P("Oct 31 to Nov 2 with Fakelu");
ok("Oct 31 to Nov 2 → 3 days", e[0]?.date === "2026-10-31" && e[0].endDate === "2026-11-02" && e[0].count === 3, e);
e = P("Oct 1-30 with Fakelu");
ok("a range of a month is not one encounter", e[0]?.endDate === e[0]?.date, e);
e = P("Oct 28 2-3 times with Fakelu");
ok("'2-3 times' is not a range", e[0]?.endDate === "2026-10-28", e);
e = P("Oct 25 with Fakeana. Oct 25 later with Fakelu");
ok("second partner same day → own entry", e.length === 2 && e[1].partnerName === "Fakelu" && e[1].date === "2026-10-25", e);
e = P("Oct 25 with Fakeana, then later with Fakelu");
ok("…also without repeating the date", e.length === 2 && e[1].partnerName === "Fakelu" && e[1].date === "2026-10-25", e);
e = P("Fakeana: Oct 25 twice, Oct 27 once\nFakelu: Oct 28 3 times");
ok("partner headings carry to every entry", e.length === 3 && e[1].partnerName === "Fakeana" && e[2].partnerName === "Fakelu", e);
e = P("#1 Oct 29 with Fakeana\n#2 Oct 30 solo\n#3 Oct 31 por mi cuenta\n#4 ayer me masturbé");
ok("solo entries are solo, never the partner", e.length === 4 && !e[0].solo && e.slice(1).every((x) => x.solo && !x.partnerName), e.map((x) => [x.partnerName, x.solo]));
e = P("solo una vez con Fakeana ayer");
ok("'solo una vez' is not a solo moment", !e[0].solo && e[0].partnerName === "Fakeana", e);
e = P("Oct 26 we were alone at last");
ok("'we were alone' is not solo", !e[0].solo, e);
e = P("Oct 29 with Fakeana at 10pm and again at 1am");
ok("again at 1am → 2 rounds, into the next day", e[0].count === 2 && e[0].nextDay && e[0].times.join() === "22:00,01:00", e);
e = P("Oct 28 at 11pm with Fakeana, went until 2am");
ok("until 2am → into the next day", e[0].nextDay && e[0].count === 1, e);
console.log(`batch-m5m8: ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
